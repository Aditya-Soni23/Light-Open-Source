const MAX_SOURCE_ROOM_NAME_BYTES = 512;
const MAX_AGORA_CHANNEL_NAME_BYTES = 64;
const CHANNEL_PREFIX = 'light_';
const FINGERPRINT_HEX_LENGTH = 24;
const READABLE_PART_MAX_LENGTH =
  MAX_AGORA_CHANNEL_NAME_BYTES - CHANNEL_PREFIX.length - 1 - FINGERPRINT_HEX_LENGTH;
const CANONICAL_CHANNEL_NAME_PATTERN = new RegExp(
  `^${CHANNEL_PREFIX}[a-zA-Z0-9_-]{1,${READABLE_PART_MAX_LENGTH}}_[a-f0-9]{${FINGERPRINT_HEX_LENGTH}}$`
);

const encoder = new TextEncoder();

function byteLength(value: string): number {
  return encoder.encode(value).byteLength;
}

function roomNameError(message: string): Error {
  return new Error(`Voice room name is invalid: ${message}`);
}

/**
 * Converts a logical LIGHT room key into an Agora-safe channel name.
 *
 * The hash is based on the complete original key, so shortening the readable
 * portion cannot silently merge two different rooms into one Agora channel.
 */
export async function normalizeVoiceChannelName(roomKey: string): Promise<string> {
  if (typeof roomKey !== 'string') {
    throw roomNameError('a room identifier is required.');
  }

  const trimmedRoomKey = roomKey.trim();
  if (!trimmedRoomKey) {
    throw roomNameError('please choose a room with a name.');
  }

  if (byteLength(trimmedRoomKey) > MAX_SOURCE_ROOM_NAME_BYTES) {
    throw roomNameError('the room name is too long. Please choose a shorter room name.');
  }

  // A channel already generated by this function is safe to use unchanged.
  if (CANONICAL_CHANNEL_NAME_PATTERN.test(trimmedRoomKey)) {
    return trimmedRoomKey;
  }

  if (!globalThis.crypto?.subtle) {
    throw roomNameError('secure channel naming is unavailable in this app. Please restart LIGHT.');
  }

  const digest = await globalThis.crypto.subtle.digest('SHA-256', encoder.encode(trimmedRoomKey));
  const fingerprint = Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0'))
    .join('')
    .slice(0, FINGERPRINT_HEX_LENGTH);

  const readablePart = trimmedRoomKey
    .normalize('NFKC')
    .replace(/[^a-zA-Z0-9_-]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, READABLE_PART_MAX_LENGTH) || 'room';
  const channelName = `${CHANNEL_PREFIX}${readablePart}_${fingerprint}`;

  // This is a defensive check: channelName only contains ASCII characters.
  if (byteLength(channelName) > MAX_AGORA_CHANNEL_NAME_BYTES) {
    throw roomNameError('the room name could not be made compatible with voice chat.');
  }

  return channelName;
}
